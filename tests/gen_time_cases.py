    ("2026-03-09 12:00", "US summer / EU winter mismatch starts"),
    ("2026-03-10 01:30", "mismatch: still previous FTMO day"),
    ("2026-03-10 02:00", "mismatch: FTMO day starts 02:00 server"),
    ("2026-03-27 12:00", "Fri, last trading day of spring mismatch"),
    ("2026-03-29 03:59", "UK/EU spring change, one minute before"),
    ("2026-03-29 04:00", "UK/EU spring change, exact"),
    ("2026-03-30 12:00", "Mon after EU spring change, both summer"),
    ("2026-07-15 00:59", "summer: still previous FTMO day"),
    ("2026-07-15 01:00", "summer: FTMO day starts 01:00 server"),
